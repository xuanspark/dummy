//  本目录的 example 桌面仿真版与 firmware/ 顶层共用同一份 Mongoose 源码。
//  原始仓库使用符号链接（symlink）指向 ../../mongoose.c；
//  Windows 上 git checkout 会把符号链接落地为纯文本占位文件，导致 Makefile
//  的 `gcc ... mongoose.c ...` 编译失败。
//
//  这里改用 C 预处理器 #include 重定向：
//   - Linux / macOS：行为与原符号链接一致（同一份源码被编译为本 TU）
//   - Windows / MinGW：可正常编译，无需手动还原符号链接
// ============================================================================
#include "../../mongoose.c"